def leakage(rep, R):
    lk = R["leakage_test"]
    rep.add(H1("4. Проверка утечки"))
    rp = lk["reproduction"]
    rows = [["Производственная колонка", "Сравнено", "Несовпадение пропусков", "Макс. |разница|"]]
    for k, v in rp.items():
        if k == "passed":
            continue
        rows.append([k, v["compared"], v["nan_pattern_mismatch"], f"{v['max_abs_diff']:.1e}"])
    rep.add(P(f"Воспроизведение производственных колонок: {'пройдено' if rp['passed'] else 'НЕ пройдено'}."))
    rep.add(*T(rows, [5.4, 3.0, 4.0, 3.4]))
    for key, title in (("future_blind_study", "Слепота к будущему — построитель исследования"),
                       ("future_blind_production", "Слепота к будущему — производственный построитель")):
        x = lk[key]
        rows = [["День отсечения D", "Матчей ≤ D", "Изменённых значений ≤ D", "Матчей > D", "Доля изменённых > D"]]
        for d, v in x["cutoffs"].items():
            rows.append([d, v["rows_on_or_before"], v["differing_cells_on_or_before"], v["rows_after"],
                         f"{v['share_rows_changed_after'] * 100:.1f}%"])
        rep.add(P(f"{title}: {x['matches']} матчей, {x['features']} признаков — "
                  f"{'пройдено' if x['passed'] else 'НЕ пройдено'}."))
        rep.add(*T(rows, [3.2, 2.6, 4.0, 2.6, 3.6]))
    o = lk["own_result"]
    rep.add(P(f"Собственный результат: из {o['matches_tested']} изменённых матчей признаки самого матча изменились у "
              f"{o['own_features_changed']}, признаки следующего матча хозяев — у {o['next_match_features_changed']} "
              f"({'пройдено' if o['passed'] else 'НЕ пройдено'})."))


def signal(rep, R):
    sig = R["signal"]
    S = sig["select"]["features"]
    rep.add(H1("5. Есть ли в новых признаках информация, которой нет в модели?"))
    rep.add(P("Остаток модели — очки хозяев минус ожидаемые моделью очки, 3·1[П1] + 1[Н] − (3p_{H} + p_{D}); остаток рынка "
              "— то же для де-маржинализированной цены. Если признак уже учтён, его корреляция с остатком ≈ 0. "
              f"Сезоны отбора: {sig['select']['n']} матчей, проверок {sig['select']['n_tests']} (признаки × остатки), "
              "поправка Холма."))
    top = sorted(S, key=lambda x: -abs(S[x]["r_model"]["rho"] or 0))[:14]
    rows = [["Признак", "r модель", "p Холма", "r рынок (откр.)", "p Холма", "r рынок (закр.)", "r голы", "2025/26 r модель"]]
    I = sig["2025"]["features"]
    for x in top:
        s = S[x]
        rows.append([x, f(s["r_model"]["rho"], 3), pv(s["r_model"]["p_holm"]), f(s["r_market"]["rho"], 3),
                     pv(s["r_market"]["p_holm"]), f(s["r_close"]["rho"], 3), f(s["r_goals"]["rho"], 3),
                     f(I[x]["r_model"]["rho"], 3)])
    rep.add(*T(rows, [3.4, 1.7, 1.7, 2.1, 1.7, 2.1, 1.6, 2.3]))
    rep.add(*figure(C.FIGURES / "signal.png", "Рис. 1. Корреляция признаков с остатками модели и рынка (2023/24 + 2024/25)."))
    rep.add(*figure(C.FIGURES / "signal_deciles.png",
                    "Рис. 2. Средний остаток очков хозяев по децилям разницы формы (95 % ДИ): модель и рынок."))
    x = top[0]
    rep.add(note(f"Методическое замечание. Ранговая корреляция (Спирмен) здесь даёт ложный «сигнал»: для {x} она "
                 f"равна {S[x]['r_model']['spearman']:+.3f} (рынок {S[x]['r_market']['spearman']:+.3f}) против "
                 f"Пирсона {S[x]['r_model']['rho']:+.3f}. Остаток трёхзначного исхода минус его ожидание асимметричен, и "
                 "его ранги смещены даже при идеально откалиброванном прогнозе; несмещённый тест — ковариация "
                 "(Пирсон), так как E[r | x] = 0 при калибровке. Прямая проверка — раздел 8."))


