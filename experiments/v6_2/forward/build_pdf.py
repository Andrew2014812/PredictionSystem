def _last_exact(w) -> str:
    exact = [x["week"] for x in w if x["diff"] is not None and abs(x["diff"]) < 1e-9]
    return exact[-1] if exact else "—"


def T(rows, widths):
    return table(rows, widths=[w * cm for w in widths])


def f(v, d=3):
    return "—" if v is None else f"{v:.{d}f}"


def pct(v, d=1):
    return "—" if v is None else f"{v * 100:+.{d}f}"


