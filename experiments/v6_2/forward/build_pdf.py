                "**Main: PS-Platt по месяцам** — (a_m, b_m) = логистическая регрессия (C = 10⁴) выигрыша на logit pc по "
                "всем рассчитанным показанным Main 2026/27 (единая история продакшна) до 1-го числа месяца матча; "
