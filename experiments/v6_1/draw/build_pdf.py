                      f"выше доли ничьих обучающих сезонов ({p(R['draw_share_cap'])}); заменить текущее правило можно, только если "
                      "macro F1 выше минимум на 0.005 на КАЖДОМ сезоне отбора, accuracy ниже не более чем на 0.5 п.п., и на 2026/27 "
                      "(блок и история) macro F1 не ниже.",
                      f"**Ничья как Main:** политика с лучшим изменением ROI Main на объединённом отборе (не менее "
