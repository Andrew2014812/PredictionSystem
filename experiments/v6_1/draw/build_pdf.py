def W(*xs):
    """Column widths in cm (the page body is 17 cm wide)."""
    return [x * cm for x in xs]


def yn(b):
    return "да" if b else "нет"


def cm_table(mat, title):
    rows = [[title, "назв. П1", "назв. Х", "назв. П2", "всего"]]
    for i, lab in enumerate(LAB):
        rows.append([f"факт {lab}", *mat[i], sum(mat[i])])
    rows.append(["всего", *[sum(r[j] for r in mat) for j in range(3)], sum(map(sum, mat))])
    return table(rows, widths=[4.2 * cm, 2.6 * cm, 2.6 * cm, 2.6 * cm, 2.4 * cm])


